<?php

namespace App\Http\Controllers;

use App\Models\AttendanceImportBatch;
use App\Models\AttendanceImportRow;
use App\Models\BiometricConnector;
use App\Models\BiometricSyncLog;
use App\Models\EmployeeProfile;
use Carbon\Carbon;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class LocalAttendanceAgentController extends Controller
{
    public function ingest(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'connector_code' => ['required', 'string', 'max:80'],
            'agent_token' => ['required', 'string', 'max:255'],
            'agent_version' => ['nullable', 'string', 'max:80'],
            'batch_id' => ['required', 'string', 'max:80'],
            'machine_code' => ['nullable', 'string', 'max:80'],
            'source_type' => ['nullable', Rule::in(['csv_folder', 'api_placeholder', 'local_app_placeholder'])],
            'source_reference' => ['nullable', 'string', 'max:255'],
            'events' => ['required', 'array', 'min:1', 'max:1000'],
            'events.*.employee_identifier' => ['required', 'string', 'max:120'],
            'events.*.employee_name' => ['nullable', 'string', 'max:255'],
            'events.*.event_time' => ['required', 'date'],
            'events.*.event_type' => ['required', 'string', 'max:40'],
            'events.*.source_device' => ['nullable', 'string', 'max:255'],
            'events.*.raw_payload' => ['nullable', 'array'],
        ]);

        $connector = $this->authenticateAgent($validated['connector_code'], $validated['agent_token']);

        if (! $connector) {
            return response()->json(['message' => 'Connector code atau token agent tidak valid.'], 401);
        }

        if ($connector->status !== 'active') {
            $this->markAgentSeen($connector, $request, [
                'status' => 'blocked',
                'reason' => 'connector_not_active',
                'agent_version' => $validated['agent_version'] ?? null,
            ]);

            return response()->json(['message' => 'Connector belum aktif atau sedang paused.'], 423);
        }

        $events = collect($validated['events']);
        $eventTimes = $events->pluck('event_time')->map(fn (string $time) => Carbon::parse($time));
        $batchNumber = 'AGENT-' . Str::upper(Str::slug($validated['batch_id'], '-'));

        $batch = AttendanceImportBatch::firstOrCreate(
            ['batch_number' => $batchNumber],
            [
                'company_id' => $connector->company_id,
                'branch_id' => $connector->branch_id,
                'source_type' => 'local_agent',
                'machine_code' => $validated['machine_code'] ?? $connector->machine_code ?? $connector->connector_code,
                'machine_name' => $connector->connector_name,
                'import_period_start' => $eventTimes->min()?->toDateString(),
                'import_period_end' => $eventTimes->max()?->toDateString(),
                'file_reference' => $validated['source_reference'] ?? $validated['source_type'] ?? 'local_agent',
                'status' => 'validated',
                'notes' => 'Generated by Local Attendance Agent ' . $connector->connector_code,
            ],
        );

        $createdRows = 0;
        $matchedRows = 0;
        $failedRows = 0;
        $duplicateRows = 0;

        foreach ($events as $event) {
            $employee = $this->resolveEmployee($event['employee_identifier']);
            $eventType = $this->normalizeEventType($event['event_type']);
            $eventAt = Carbon::parse($event['event_time']);
            $sourceDevice = $event['source_device'] ?? $validated['machine_code'] ?? $connector->machine_code ?? $connector->connector_code;

            $exists = AttendanceImportRow::query()
                ->where('attendance_import_batch_id', $batch->id)
                ->where('raw_identifier', $event['employee_identifier'])
                ->where('event_type', $eventType)
                ->where('event_at', $eventAt)
                ->where('source_device', $sourceDevice)
                ->exists();

            if ($exists) {
                $duplicateRows++;
                continue;
            }

            $flags = $this->anomalyFlags($employee, $eventType, $eventAt);

            AttendanceImportRow::create([
                'attendance_import_batch_id' => $batch->id,
                'employee_profile_id' => $employee?->id,
                'employee_number' => $employee?->employee_number ?: $event['employee_identifier'],
                'employee_name' => $employee?->full_name ?: ($event['employee_name'] ?? null),
                'raw_identifier' => $event['employee_identifier'],
                'event_type' => $eventType,
                'event_at' => $eventAt,
                'source_device' => $sourceDevice,
                'match_status' => $flags === [] ? 'matched' : 'needs_review',
                'anomaly_flags' => $flags,
                'normalized_payload' => [
                    'connector_code' => $connector->connector_code,
                    'agent_version' => $validated['agent_version'] ?? null,
                    'source_type' => $validated['source_type'] ?? 'csv_folder',
                    'raw_payload' => $event['raw_payload'] ?? [],
                ],
                'notes' => 'Pushed by Local Attendance Agent.',
            ]);

            $createdRows++;
            $flags === [] ? $matchedRows++ : $failedRows++;
        }

        $this->refreshBatchCounts($batch);

        $log = BiometricSyncLog::create([
            'biometric_connector_id' => $connector->id,
            'attendance_import_batch_id' => $batch->id,
            'sync_number' => 'AGENT-SYNC-' . now()->format('YmdHis') . '-' . $connector->id,
            'started_at' => now(),
            'finished_at' => now(),
            'status' => $failedRows > 0 ? 'partial_success' : 'success',
            'pulled_rows' => $events->count(),
            'matched_rows' => $matchedRows,
            'failed_rows' => $failedRows,
            'payload_summary' => [
                'batch_id' => $validated['batch_id'],
                'created_rows' => $createdRows,
                'duplicate_rows' => $duplicateRows,
                'source_type' => $validated['source_type'] ?? 'csv_folder',
                'source_reference' => $validated['source_reference'] ?? null,
            ],
            'message' => 'Data diterima dari Local Attendance Agent.',
        ]);

        $connector->forceFill([
            'last_sync_at' => $log->finished_at,
            'agent_last_seen_at' => now(),
            'agent_last_ip' => $request->ip(),
            'agent_version' => $validated['agent_version'] ?? $connector->agent_version,
            'agent_status' => $failedRows > 0 ? 'synced_with_anomaly' : 'online',
            'status' => 'active',
            'agent_heartbeat_count' => $connector->agent_heartbeat_count + 1,
            'agent_last_payload' => [
                'type' => 'ingest',
                'batch_id' => $validated['batch_id'],
                'machine_code' => $validated['machine_code'] ?? null,
                'source_type' => $validated['source_type'] ?? 'csv_folder',
                'received_rows' => $events->count(),
                'created_rows' => $createdRows,
                'duplicate_rows' => $duplicateRows,
                'failed_rows' => $failedRows,
                'received_at' => now()->toIso8601String(),
            ],
        ])->save();

        return response()->json([
            'message' => 'Clock event agent diterima.',
            'batch_number' => $batch->batch_number,
            'sync_number' => $log->sync_number,
            'received_rows' => $events->count(),
            'created_rows' => $createdRows,
            'matched_rows' => $matchedRows,
            'failed_rows' => $failedRows,
            'duplicate_rows' => $duplicateRows,
        ]);
    }

    public function heartbeat(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'connector_code' => ['required', 'string', 'max:80'],
            'agent_token' => ['required', 'string', 'max:255'],
            'agent_version' => ['nullable', 'string', 'max:80'],
            'machine_code' => ['nullable', 'string', 'max:80'],
            'status' => ['nullable', Rule::in(['online', 'idle', 'syncing', 'warning', 'error'])],
            'local_time' => ['nullable', 'date'],
            'source_type' => ['nullable', Rule::in(['csv_folder', 'api_placeholder', 'local_app_placeholder'])],
            'source_reference' => ['nullable', 'string', 'max:255'],
            'metrics' => ['nullable', 'array'],
        ]);

        $connector = $this->authenticateAgent($validated['connector_code'], $validated['agent_token']);

        if (! $connector) {
            return response()->json(['message' => 'Connector code atau token agent tidak valid.'], 401);
        }

        $agentStatus = $connector->status === 'active'
            ? ($validated['status'] ?? 'online')
            : 'blocked';

        $this->markAgentSeen($connector, $request, [
            'type' => 'heartbeat',
            'status' => $agentStatus,
            'agent_version' => $validated['agent_version'] ?? null,
            'machine_code' => $validated['machine_code'] ?? null,
            'source_type' => $validated['source_type'] ?? null,
            'source_reference' => $validated['source_reference'] ?? null,
            'local_time' => $validated['local_time'] ?? null,
            'metrics' => $validated['metrics'] ?? [],
            'received_at' => now()->toIso8601String(),
        ]);

        BiometricSyncLog::create([
            'biometric_connector_id' => $connector->id,
            'sync_number' => 'AGENT-HB-' . now()->format('YmdHis') . '-' . $connector->id,
            'started_at' => now(),
            'finished_at' => now(),
            'status' => $agentStatus === 'blocked' ? 'blocked' : 'heartbeat',
            'pulled_rows' => 0,
            'matched_rows' => 0,
            'failed_rows' => 0,
            'payload_summary' => [
                'agent_version' => $validated['agent_version'] ?? null,
                'machine_code' => $validated['machine_code'] ?? null,
                'source_type' => $validated['source_type'] ?? null,
                'status' => $agentStatus,
            ],
            'message' => $agentStatus === 'blocked'
                ? 'Heartbeat diterima, tetapi connector belum aktif.'
                : 'Heartbeat Local Attendance Agent diterima.',
        ]);

        return response()->json([
            'message' => $agentStatus === 'blocked'
                ? 'Heartbeat diterima, tetapi connector belum aktif.'
                : 'Heartbeat agent diterima.',
            'connector_code' => $connector->connector_code,
            'agent_status' => $agentStatus,
            'server_time' => now()->toIso8601String(),
            'next_sync_at' => $connector->fresh()->next_sync_at?->toIso8601String(),
        ], $agentStatus === 'blocked' ? 423 : 200);
    }

    private function resolveEmployee(string $identifier): ?EmployeeProfile
    {
        $query = EmployeeProfile::query()->where('employee_number', $identifier);

        if (Schema::hasColumn('employee_profiles', 'nik')) {
            $query->orWhere('nik', $identifier);
        }

        return $query->first();
    }

    private function authenticateAgent(string $connectorCode, string $agentToken): ?BiometricConnector
    {
        $connector = BiometricConnector::query()
            ->where('connector_code', $connectorCode)
            ->where('connection_type', 'local_agent')
            ->first();

        if (! $connector || ! $connector->agent_token_hash || ! Hash::check($agentToken, $connector->agent_token_hash)) {
            return null;
        }

        return $connector;
    }

    private function markAgentSeen(BiometricConnector $connector, Request $request, array $payload): void
    {
        $status = $payload['status'] ?? 'online';

        $connector->forceFill([
            'agent_last_seen_at' => now(),
            'agent_last_ip' => $request->ip(),
            'agent_version' => $payload['agent_version'] ?? $connector->agent_version,
            'agent_status' => $status,
            'agent_heartbeat_count' => $connector->agent_heartbeat_count + 1,
            'agent_last_payload' => $payload,
        ])->save();
    }

    private function normalizeEventType(string $eventType): string
    {
        return match (Str::lower(str_replace(['-', ' '], '_', $eventType))) {
            'clock_out', 'checkout', 'out' => 'clock_out',
            'break_start', 'breakout' => 'break_start',
            'break_end', 'breakin' => 'break_end',
            default => 'clock_in',
        };
    }

    private function anomalyFlags(?EmployeeProfile $employee, string $eventType, Carbon $eventAt): array
    {
        $flags = [];

        if (! $employee) {
            $flags[] = 'employee_not_found';
        }

        if ($employee && AttendanceImportRow::query()
            ->where('employee_profile_id', $employee->id)
            ->where('event_at', $eventAt)
            ->where('event_type', $eventType)
            ->exists()) {
            $flags[] = 'duplicate_event';
        }

        return $flags;
    }

    private function refreshBatchCounts(AttendanceImportBatch $batch): void
    {
        $rows = $batch->rows();

        $batch->forceFill([
            'imported_rows' => (clone $rows)->count(),
            'matched_rows' => (clone $rows)->where('match_status', 'matched')->count(),
            'anomaly_rows' => (clone $rows)->where('match_status', '!=', 'matched')->count(),
            'status' => (clone $rows)->where('match_status', '!=', 'matched')->exists() ? 'validated' : 'reconciled',
        ])->save();
    }
}
